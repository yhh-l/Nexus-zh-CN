// Reproduce the application catalog from the reviewed, fixed English baseline.
import { readFile, writeFile } from 'node:fs/promises'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { EN } from '../../ui/src/i18n/en.ts'

if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node integrate.mjs [--check]')
async function output(url, text) {
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== text) throw new Error(`Generated output is stale: ${url.pathname}`)
  } else await writeFile(url, text)
}
execFileSync(process.execPath, [fileURLToPath(new URL('verify.mjs', import.meta.url)), '--require-complete'], { stdio: 'inherit' })
const data = JSON.parse(await readFile(new URL('nexus-zh-CN.json', import.meta.url), 'utf8'))
if (data.meta.commit !== 'deef912340bade1a9961a2c0cfb3979cde9b1ee4' || data.meta.version !== '1.19.0') throw new Error('Unexpected baseline')
const rows = new Map(data.rows.map(row => [row.id, row]))
const catalog = Object.fromEntries(Object.entries(EN).map(([key, value]) => [key,
  typeof value === 'string' ? rows.get(key).chinese : Object.fromEntries(Object.keys(value).map(form => [form, rows.get(`${key}::${form}`).chinese])),
]))
await output(new URL('../../ui/src/i18n/zh-CN.ts', import.meta.url),
  '// Simplified Chinese. Generated by translations/zh-CN/integrate.mjs; edit the reviewed source.\n' +
  "import type { PartialCatalog } from './index'\n\n" +
  `export const ZH_CN = ${JSON.stringify(catalog, null, 2)} satisfies PartialCatalog\n`)
const splashUrl = new URL('../../ui/public/splashscreen.html', import.meta.url)
const html = await readFile(splashUrl, 'utf8')
const pattern = /(<script type="application\/json" id="splash-strings">)\s*([\s\S]*?)(\s*<\/script>)/
const strings = JSON.parse(html.match(pattern)[2])
strings['zh-CN'] = Object.fromEntries(Object.keys(strings.en).map(key => [key, rows.get(`splashscreen.${key}`).chinese]))
await output(splashUrl, html.replace(pattern, (_, start, _json, end) => `${start}\n${JSON.stringify(strings, null, 2).split('\n').map(line => '      ' + line).join('\n')}\n    ${end.trimStart()}`))
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Integrated'} ${Object.keys(catalog).length} keys and 5 splash strings.`)
